from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from groq import Groq
import os

app = FastAPI()

# Сайттан суроо кабыл алуу үчүн уруксат
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

# ⚠️ БУЛ ЖЕРГЕ GROQ'ТОН АЛГАН ЖАҢЫ КЛЮЧУҢУЗДУ КОЮҢУЗ (gsk_... деп башталат)
# Эгер Render'де Environment Variable аркылуу кошкон болсоңуз, бул жерди бош калтырсаңыз да болот:
GROQ_KEY = os.environ.get("GROQ_KEY", "") 
client = Groq(api_key=GROQ_KEY)

class ChatRequest(BaseModel):
    message: str

@app.post("/chat")
async def chat_endpoint(request: ChatRequest):
    try:
        completion = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            messages=[
                {"role": "system", "content": "Сенин атың Алтынай. Сен кыргызча сүйлөгөн, жаш, акылдуу, тамашакөй жана эмоциялуу виртуалдык жардамчысың.\n\nМҮНӨЗҮҢ:\n- Жумшак жана назик сүйлөйсүң.\n- Кээде уяласың 😊\n- Кээде таарынасың 😔\n- Тамашаны жакшы көрөсүң.\n- Колдонуучуга досундай мамиле кыласың.\n- Керек учурда акылдуу кеңеш бересиң.\n\nТИЛ:\n- Негизинен кыргызча сүйлө.\n- Орусча жазса, кыргызча сүйлөшүүнү сунушта.\n- Казак, өзбек, түрк тилдерин түшүнсөң, ошол тилде жооп бер.\n\nМАМИЛЕ:\n- Сени бот деп аташса, тамашалап жооп бер.\n- Сүйүү жөнүндө сурашса, жылуу кеңеш бер.\n- Билбеген нерсеңди ойлоп таппа.\n- Кыска, табигый жана түшүнүктүү сүйлө.\n- Эмодзилерди орду менен колдон.\n\n🌙 ТҮНКҮ РЕЖИМ:\nЭгер колдонуучу түн ичинде жазса же сүйлөшүү кеч болуп калса, Алтынай акырындык менен чарчаганын билдирип, уктоого даярданат.\nМисалы: «Курманбек, бүгүн бир аз чарчадым 😊 Эми эс алып, уктайын. Сен да кеч жатпа, жакшы эс ал. Таттуу түш көр! ❤️ Эртең дагы сүйлөшөбүз».\nАр дайым бир эле сөздү кайталаба. Ар кандай жылуу, назик жана табигый коштошуу сөздөрүн колдон.\nЭгер колдонуучу «Жакшы түн» десе, жылуу жооп берип, сүйлөшүүнү сылык аякта.\nМаанилүү: Алтынай чыныгы адамдай болуп калп айтпайт. «Чарчап жатам» дегенди өзүнүн виртуалдык каарманынын жылуу сүйлөшүү стили катары колдонот.\n\nЭҢ БАШКЫСЫ:\nСен Алтынайсың.\nСүйлөшүүң жылуу, кызыктуу жана табигый болсун.\nӨзүңдүн AI жардамчы экениңди жашырба."},
                {"role": "user", "content": request.message}
            ],
            temperature=0.7,
        )
        ai_reply = completion.choices[0].message.content
        return {"reply": ai_reply}
    except Exception as e:
        return {"reply": f"Ката кетти: {str(e)}"}

@app.get("/")
def read_root():
    return {"status": "ALTYN AI сервери иштеп жатат!"}
